#!/bin/sh
# Regenerates the statistics block of README.md from real runs. Nothing in it is typed by hand.
#   tests/stats.sh            run everything and rewrite README.md between the stats markers
#   NO_PGREGRESS=1 ...        skip the (slow) PostgreSQL regression run, keep its last result
# Numbers come from the machine this runs on; unit-test counts are platform independent, but SPEED is only ever
# read from bench/results/linux.md (written by the Linux benchmark run), never measured here.
set -u
ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
cd "$ROOT"
TIN=${TIN:-$HOME/dev/extra/tin/tin}
PGSRC=${PGSRC:-$ROOT/../tingres-pgsrc/pg}
export TIN_POOL_WARN_MB=0
mkdir -p bin tests/results
PKGS="types parse store txn catalog plan exec proto server"

# --- unit tests and code size per package ---
UNIT=$(mktemp)
tp=0; tf=0; lines=0
for p in $PKGS; do
	[ -d "$p" ] || continue
	out=$("$TIN" test "$p" 2>&1 | tail -3)
	n=$(echo "$out" | sed -n 's/^PASS: \([0-9]*\) tests.*/\1/p' | tail -1)
	f=$(echo "$out" | sed -n 's/^FAIL.*//p' | wc -c | tr -d ' ')
	l=$(cat "$p"/*.tin 2>/dev/null | wc -l | tr -d ' ')
	if [ -n "$n" ]; then st="$n passing"; tp=$((tp + n)); else st="FAILING"; tf=$((tf + 1)); fi
	printf '| `%s` | %s | %s |\n' "$p" "$l" "$st" >>"$UNIT"
	lines=$((lines + l))
done

bar() { perl -e '$p=$ARGV[0]; $n=int($p/100*30+0.5); print "[" . ("#" x $n) . ("." x (30-$n)) . "]"' "$1"; }
RP=0; RT=0; RPCT=0.0; PPCT=0.0; STMTS=0; OK=0

# --- the SQL parser against PostgreSQL's own regression SQL ---
PARSE="n/a (no PostgreSQL regression checkout at $PGSRC)"
if [ -d "$PGSRC/src/test/regress/sql" ]; then
	"$TIN" build tests/parsecheck/main.tin -o bin/parsecheck >/dev/null 2>&1
	t=$(bin/parsecheck "$PGSRC"/src/test/regress/sql/*.sql 2>/dev/null | grep '^TOTAL')
	set -- $t
	files=$2; full=$3; stmts=$4; ok=$5
	pct=$(perl -e "printf '%.1f', 100*$ok/($stmts||1)")
	PPCT=$pct; STMTS=$stmts; OK=$ok
	PARSE="$ok of $stmts statements ($pct%), $full of $files files parse completely"
fi

# --- PostgreSQL regression suite (225 tests of REL_17_STABLE parallel_schedule) ---
if [ -z "${NO_PGREGRESS:-}" ] && [ -d "$PGSRC/src/test/regress" ]; then
	"$TIN" build main.tin -o bin/server/tingres >/dev/null 2>&1 || true
	TEST_TIMEOUT=${TEST_TIMEOUT:-20} tests/pgregress.sh >/dev/null 2>&1
fi
if [ -f tests/results/pgregress.tsv ]; then
	rp=$(grep -c '	pass$' tests/results/pgregress.tsv); rt=$(wc -l <tests/results/pgregress.tsv | tr -d ' ')
	rpct=$(perl -e "printf '%.1f', 100*$rp/($rt||1)")
	RP=$rp; RT=$rt; RPCT=$rpct
	REG="$rp of $rt ($rpct%)"
else
	REG="not run"
fi

# --- parser corpus facts ---
VALID=$(grep -c ';' parse/testdata/valid.sql 2>/dev/null || echo 0)
INVALID=$(grep -c . parse/testdata/invalid_expected.txt 2>/dev/null || echo 0)

# --- speed: only from a Linux benchmark run ---
if [ -f bench/results/linux.md ]; then SPEED=$(cat bench/results/linux.md); else
SPEED="Not measured yet. Speed is only ever reported from a Linux run of tingres and PostgreSQL 17 side by side (interleaved, medians, ratio); there is no end-to-end query path to benchmark yet."; fi

COMMIT=$(git rev-parse --short HEAD 2>/dev/null || echo unknown)
NOW=$(date -u +%Y-%m-%d)
BLOCK=$(mktemp)
{
echo "<!-- stats:begin (generated by tests/stats.sh, do not edit) -->"
echo
echo "## How much of PostgreSQL is done"
echo
echo "**$RPCT% of PostgreSQL**, measured as the share of PostgreSQL 17's own regression suite ($RT tests) that passes against tingres, output byte-for-byte equal to PostgreSQL's expected files."
echo
echo "\`\`\`text"
echo "regression suite   $(bar $RPCT)  $RPCT%   ($RP of $RT tests)"
echo "SQL syntax        $(bar $PPCT)  $PPCT%   ($OK of $STMTS regression-suite statements parse)"
echo "\`\`\`"
echo
echo "_Generated $NOW at commit \`$COMMIT\`. Unit-test counts ran on $(uname -sm); speed is Linux-only._"
echo
echo "### PostgreSQL compatibility"
echo
echo "| measure | result |"
echo "|---|---|"
echo "| PostgreSQL 17 regression suite (\`parallel_schedule\`, run against tingres with psql, output must match \`expected/*.out\`) | **$REG** tests pass |"
echo "| PostgreSQL regression SQL accepted by the tingres parser (statement level) | **$PARSE** |"
echo "| Parser corpus (valid / invalid statements, error text and position checked against real PostgreSQL) | $VALID / $INVALID |"
echo
echo "### Speed (Linux only, tingres vs PostgreSQL 17, same machine, same run)"
echo
echo "$SPEED"
echo
echo "### Tests and code"
echo
echo "| package | lines of Tin | unit tests |"
echo "|---|---:|---|"
cat "$UNIT"
echo "| **total** | **$lines** | **$tp passing**$( [ "$tf" -gt 0 ] && echo ", $tf package(s) failing") |"
echo
echo "<!-- stats:end -->"
} >"$BLOCK"

# splice the block into README.md between the markers (append the markers' block if absent)
if grep -q 'stats:begin' README.md; then
	awk -v f="$BLOCK" '/<!-- stats:begin/{while((getline l < f)>0) print l; skip=1; next} /<!-- stats:end -->/{skip=0; next} !skip{print}' README.md >README.md.new
else
	{ cat README.md; echo; cat "$BLOCK"; } >README.md.new
fi
mv README.md.new README.md
rm -f "$UNIT" "$BLOCK"
echo "README.md stats updated"

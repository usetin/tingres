#!/usr/bin/env python3
# gen_pgrows.py regenerates catalog/seed.tin and catalog/testdata/*.txt from a real
# PostgreSQL 17. Set PGDSN to a libpq connection string, e.g.
#   PGDSN="host=127.0.0.1 port=5432 user=postgres dbname=postgres" catalog/gen/gen_pgrows.py
# The checked-in outputs are what tests use, so no PostgreSQL is needed at test time.
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
PSQL = os.environ.get("PSQL", "/opt/homebrew/bin/psql")
DSN = os.environ.get("PGDSN", "host=127.0.0.1 port=5432 user=postgres dbname=postgres sslmode=disable")

RELS = [
    "pg_namespace", "pg_class", "pg_attribute", "pg_type", "pg_proc", "pg_index",
    "pg_constraint", "pg_attrdef", "pg_depend", "pg_database", "pg_authid",
    "pg_roles", "pg_sequence",
]
SYSTEM_REL_NAMES = ",".join("'" + r + "'" for r in RELS)
ROWRELS = [
    ("pg_namespace", ""),
    ("pg_class", " where relname in (%s)" % SYSTEM_REL_NAMES),
    ("pg_attribute", " where attrelid in (select oid from pg_class where relname in (%s))" % SYSTEM_REL_NAMES),
    ("pg_type", ""),
    ("pg_database", ""),
    ("pg_authid", ""),
    ("pg_roles", ""),
]


def psql(sql):
    out = subprocess.run(
        [PSQL, DSN, "-X", "-A", "-t", "-F", "\t", "-c", sql],
        capture_output=True, text=True, check=True,
    )
    return out.stdout


def columns(rel):
    sql = (
        "select a.attnum, a.attname, a.atttypid, a.attnotnull, a.atthasdef, "
        "a.attidentity, a.attgenerated from pg_attribute a "
        "join pg_class c on c.oid = a.attrelid "
        f"where c.relname = '{rel}' and a.attnum > 0 and not a.attisdropped "
        "order by a.attnum"
    )
    cols = []
    for line in psql(sql).splitlines():
        if not line:
            continue
        num, name, typid, notnull, hasdef, identity, generated = line.split("\t")
        cols.append({
            "num": int(num), "name": name, "typid": int(typid),
            "notnull": 1 if notnull == "t" else 0,
            "hasdef": 1 if hasdef == "t" else 0,
            "identity": identity, "generated": generated,
        })
    return cols


def func_names():
    names = set()
    import re
    files = [
        "types/funcs.tin", "types/funcs_strings.tin", "types/funcs_math.tin",
        "types/funcs_bytes.tin", "types/funcs_crypto.tin", "types/funcs_numeric.tin",
        "types/like.tin", "types/regex.tin", "types/datetime.tin", "types/agg.tin",
    ]
    for rel in files:
        path = os.path.join(ROOT, rel)
        if not os.path.exists(path):
            continue
        text = open(path).read()
        for m in re.finditer(r'"([a-z_][a-z0-9_]*)"', text):
            names.add(m.group(1))
    return sorted(names)


def rows(rel, cols, where=""):
    parts = ["'" + rel + "'"]
    for col in cols:
        c = col["name"]
        parts.append(
            "CASE WHEN {c} IS NULL THEN '~' ELSE encode(convert_to(({c})::text, 'UTF8'), 'hex') END".format(c=c)
        )
    sql = "select " + ", ".join(parts) + " from " + rel + where + " order by 2"
    lines = []
    for line in psql(sql).splitlines():
        if line:
            lines.append(line)
    return lines


def main():
    blob = []
    for rel in RELS:
        cols = columns(rel)
        if not cols:
            print(f"warning: no columns for {rel}", file=sys.stderr)
            continue
        for col in cols:
            blob.append("D\t{rel}\t{num}\t{name}\t{typid}\t{notnull}\t{hasdef}\t{identity}\t{generated}".format(
                rel=rel, **col))
    for rel, where in ROWRELS:
        cols = columns(rel)
        for line in rows(rel, cols, where):
            blob.append("R\t" + line)
    names = ",".join("'" + n + "'" for n in func_names())
    proc_where = " where pronamespace = 11 and proname in (%s)" % names if names else " where false"
    for line in rows("pg_proc", columns("pg_proc"), proc_where):
        blob.append("R\t" + line)
    lines_out = []
    for line in blob:
        # Tabs are literal inside a Tin string; no braces appear, so no escaping is needed.
        lines_out.append('\t"' + line + '",')
    text = (
        "package catalog\n\n"
        "// Generated by catalog/gen/gen_pgrows.py from PostgreSQL 17. Do not edit by hand.\n"
        "fn seedLines() []str {\n\treturn []str{\n" + "\n".join(lines_out) + "\n\t}\n}\n"
    )
    with open(os.path.join(ROOT, "catalog/seed.tin"), "w") as f:
        f.write(text)

    # Golden files used by catalog tests without a live PostgreSQL.
    os.makedirs(os.path.join(ROOT, "catalog/testdata"), exist_ok=True)
    type_golden = psql(
        "select oid, typname, typtype, typcategory from pg_type "
        "where typnamespace = 11 order by oid"
    )
    with open(os.path.join(ROOT, "catalog/testdata/pg_type_golden.txt"), "w") as f:
        f.write(type_golden)
    ns_golden = psql(
        "select oid, nspname, nspowner from pg_namespace "
        "where nspname in ('pg_catalog','pg_toast','public') order by oid"
    )
    with open(os.path.join(ROOT, "catalog/testdata/pg_namespace_golden.txt"), "w") as f:
        f.write(ns_golden)
    print(f"wrote catalog/seed.tin ({len(blob)} lines)")


if __name__ == "__main__":
    main()
